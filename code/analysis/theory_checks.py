"""Three theory checks on the Twist, computed (not asserted). Writes theory_checks.json; THEORY_T1_T3_STABILITY.md
explains them. Units: reduced Planck mass M_Pl = 1; energy densities in units of today's critical density.
    python theory_checks.py        (needs sympy for part C; parts A and B are plain arithmetic)

A. T1, one field or two: can ONE field carry both roles with V = early term + late term?
   After the early episode the field sits at the early term's minimum. The late role needs it to roll by
   delta_phi = 0.08-0.20 (our corrected fits). The early term, Lambda1^4 [1 - cos(phi/F1)]^3, then costs energy.
   Compare that cost with today's dark energy.
B. Radiative stability: the field touches matter only through c(phi) d_mu phi J5^mu = d_mu G(phi) J5^mu. Matter
   loops therefore depend on phi only through dG, so they generate kinetic terms, never a potential. Size of the
   kinetic renormalisation from the heaviest fermion (top quark), with a generous logarithm.
C. T3, non-minimal coupling (Torres-Gomez & Krasnov, arXiv:0811.1998 eq. 16): the extra piece is a total derivative
   times the vector current, so it vanishes for conserved currents. Checked symbolically, together with the Holst
   axial coefficient sqrt(6)/(4 cosh chi) used in B4."""
import json
import math

OM, OR, OL = 0.31, 9.1e-5, 0.69                     # density parameters today (Planck-like, flat)
EARLY = [  # (label, F1, theta_i, f_EDE at z_c, omega_b, omega_cdm) from the stored early fits
    ("Planck locked (width_edelockP.json)", 0.13910, 2.7736, 0.07801, 0.0226, 0.1260),
    ("P-ACT locked (width_pact_edelock.json)", 0.14768, 2.7115, 0.07530, 0.0226, 0.1264),
]
LATE_DPHI = {"Pantheon+ best (F = 2.51)": 0.0834, "DES Y5 best (F = 1.00)": 0.2022}   # b4_delta_theta.json


def z_eq(wb, wc):
    return (wb + wc) / (2.4728e-5 * (1 + 0.22711 * 3.044)) - 1


def part_a():
    out = []
    for label, F1, th, f, wb, wc in EARLY:
        zc = z_eq(wb, wc)
        a = 1 / (1 + zc)
        rho_tot = OM * a ** -3 + OR * a ** -4                     # matter + radiation dominate at z_c
        lam4 = f * rho_tot / (1 - math.cos(th)) ** 3              # V(phi_i) ~ f * rho_tot at the onset
        allowed = F1 * (8 * 0.1 * OL / lam4) ** (1 / 6)           # roll at which the early term costs 10% of DE
        for lab2, dphi in LATE_DPHI.items():
            cost = lam4 * (1 - math.cos(dphi / F1)) ** 3
            out.append({"early": label, "late": lab2, "z_c": round(zc), "Lambda1^4 / rho_crit0": lam4,
                        "late roll needed": dphi, "late roll allowed (10% of DE)": allowed,
                        "early-term energy at the needed roll / rho_DE": cost / OL})
    return out


def part_b():
    mt, MPL = 172.69, 2.435e18                                    # GeV
    c2 = 6 / 16                                                  # c = sqrt(6)/4 in Planck units (Nieh-Yan form)
    log = math.log(MPL / mt)
    dz = c2 * (mt / MPL) ** 2 * 3 / (4 * math.pi ** 2) * log    # N_c = 3, one loop, generous log
    return {"potential generated by matter loops": 0.0,
            "reason": "the coupling is d_mu G(phi) J5^mu; matter loops depend on phi only through dG",
            "kinetic renormalisation from the top quark (upper estimate)": dz}


def part_c():
    try:
        import sympy as sp
    except ImportError:
        return {"skipped": "sympy not installed"}
    g, al, chi = sp.symbols("gamma alpha chi", real=True)
    vector_piece = sp.Rational(3, 4) * al * g / (g ** 2 + 1)               # coefficient of d_mu gamma V^mu (eq. 16)
    potential = sp.Rational(3, 8) * al * sp.log(g ** 2 + 1)
    axial = sp.Rational(3, 4) / (g ** 2 + 1)                               # coefficient of d_mu gamma A^mu (eq. 16)
    axial_chi = sp.simplify(axial.subs(g, sp.sinh(chi)) * sp.cosh(chi))    # d gamma = cosh chi d chi
    axial_phi = sp.simplify(axial_chi * sp.sqrt(sp.Rational(2, 3)))        # chi = sqrt(2/3) phi (canonical)
    return {"vector piece is a total derivative": sp.simplify(sp.diff(potential, g) - vector_piece) == 0,
            "vector piece": "d_mu[(3 alpha/8) ln(gamma^2+1)] V^mu -> -(...) d_mu V^mu = 0 for a conserved current",
            "axial coefficient per d phi": str(axial_phi),
            "matches sqrt(6)/(4 cosh chi)": sp.simplify(axial_phi - sp.sqrt(6) / (4 * sp.cosh(chi))) == 0,
            "axial part independent of alpha": True}


res = {"A_T1_one_field": part_a(), "B_radiative_stability": part_b(), "C_T3_nonminimal": part_c()}
json.dump(res, open("theory_checks.json", "w"), indent=1, default=str)
for r in res["A_T1_one_field"]:
    print(f"A  {r['early'][:22]:22s} | {r['late']:24s} | needed {r['late roll needed']:.3f} vs allowed "
          f"{r['late roll allowed (10% of DE)']:.4f} | early-term cost = {r['early-term energy at the needed roll / rho_DE']:.2e} x DE")
print("B ", {k: v for k, v in res["B_radiative_stability"].items() if k != "reason"})
print("C ", res["C_T3_nonminimal"])
